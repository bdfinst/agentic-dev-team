"""Recorded-diff adapter for the /code-review benchmark harness (#2051).

Unlike the Defects4J/BugsJS adapters, this adapter's cases are not real
defects with a known fix location — Defects4J/BugsJS structurally cannot
produce a `diff_shape: "test-only"` case (#1964's blocker), because both
datasets are real production bug fixes. This adapter instead loads a
directory of *recorded* diffs — saved test-file changes, most usefully real
`/test-improve` Phase-5 diffs under the default `refactor-mode:
no-refactor` — so the harness can dispatch `/code-review` against them and
give #1964 real `diff_shape: "test-only"` `review-value.jsonl` rows. It has
no ground-truth defect location, so it never scores recall — see
`runner.run_recorded_diff_case()`, not `runner.run_case()`.

Each case is a subdirectory of `diffs_dir`::

    <diffs_dir>/<case-id>/
        meta.json     # {"description": str (optional)}
        files/        # the post-diff file tree to review, relative paths
                       # preserved (e.g. files/tests/test_foo.py)

`diff_shape` is never taken on faith from `meta.json` — it is always
(re)computed from the `files/` tree's relative paths via
`skills/code-review/scripts/change_shape.py`'s `is_test_only()`, the same
classifier `/code-review` itself uses ("classified by change_shape.py's
isTestOnly, never by eye" — `knowledge/telemetry-schema.md`'s `diff_shape`
field). A case whose `files/` tree is not provably test-only classifies as
`"mixed"` rather than being silently mislabeled.
"""

from __future__ import annotations

import importlib.util
import json
import shutil
from pathlib import Path
from typing import Any

from .common import BenchmarkCase

_change_shape_module: Any = None


def _load_change_shape():
    """Import `skills/code-review/scripts/change_shape.py` by file path.

    Mirrors `runner._load_isolated_dispatch()`'s pattern: this module lives
    under a plugin skill's `scripts/` dir, not a normally importable
    package, so the path is resolved relative to the repo root rather than
    assuming it's on `sys.path`. Cached at module scope — every case in a
    sweep re-imports the same file otherwise.
    """
    global _change_shape_module
    if _change_shape_module is not None:
        return _change_shape_module
    repo_root = Path(__file__).resolve().parents[3]
    module_path = (
        repo_root
        / "plugins"
        / "dev-team"
        / "skills"
        / "code-review"
        / "scripts"
        / "change_shape.py"
    )
    spec = importlib.util.spec_from_file_location("change_shape", module_path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load change_shape from {module_path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    _change_shape_module = module
    return module


def detect(diffs_dir: str | None) -> bool:
    """True when `diffs_dir` exists and has at least one case (a subdirectory
    with a `files/` tree)."""
    if not diffs_dir:
        return False
    root = Path(diffs_dir)
    if not root.is_dir():
        return False
    return any((child / "files").is_dir() for child in root.iterdir() if child.is_dir())


def _relative_files(files_dir: Path) -> list[str]:
    """Every file under `files_dir`, relative-posix-pathed, excluding
    `__pycache__` byte-compiled artifacts. A recorded diff's `files/` tree
    represents the files the diff actually touched; a `.pyc` generated by
    something importing a `.py` fixture (e.g. a broad `pytest` collection
    sweep — see `fixtures/conftest.py`) is never one of them, and letting it
    through would corrupt `is_test_only()`'s classification (a `.pyc` isn't
    provably a test file, so one stray cache entry flips a real test-only
    case to `mixed`)."""
    return sorted(
        str(p.relative_to(files_dir).as_posix())
        for p in files_dir.rglob("*")
        if p.is_file() and "__pycache__" not in p.parts
    )


def list_cases(diffs_dir: str) -> list[BenchmarkCase]:
    """One `BenchmarkCase` per `<diffs_dir>/<case-id>/` subdirectory carrying
    a `files/` tree. Cases without one are skipped (not a case, not an
    error — a stray file or an in-progress case directory)."""
    change_shape = _load_change_shape()
    root = Path(diffs_dir)
    cases: list[BenchmarkCase] = []
    for child in sorted(root.iterdir()):
        if not child.is_dir():
            continue
        files_dir = child / "files"
        if not files_dir.is_dir():
            continue
        rel_files = _relative_files(files_dir)
        diff_shape = "test-only" if change_shape.is_test_only(rel_files) else "mixed"
        meta_path = child / "meta.json"
        description = None
        if meta_path.is_file():
            try:
                meta = json.loads(meta_path.read_text(encoding="utf-8"))
                description = meta.get("description")
            except (json.JSONDecodeError, OSError):
                description = None
        cases.append(
            BenchmarkCase(
                dataset="recorded-diff",
                project="test-improve-phase-5",
                bug_id=child.name,
                language="multi",
                ground_truth_files=[],
                ground_truth_hunks=[],
                description=description,
                extra={"diff_shape": diff_shape, "files_dir": str(files_dir)},
            )
        )
    return cases


def checkout(case: Any, workdir: str, *, diffs_dir: str | None = None) -> bool:
    """Materialize the case's recorded `files/` tree into `workdir`.

    `case` is either a `BenchmarkCase` or its `to_dict()` form (matching
    every other adapter's `checkout()` contract). `diffs_dir` is accepted
    but unused when `case["extra"]["files_dir"]` is already an absolute
    path (the normal case from `list_cases()`) — kept for interface
    symmetry with the Defects4J/BugsJS adapters, whose `checkout()` needs
    the dataset home to resolve a case.
    """
    extra = case.extra if hasattr(case, "extra") else case.get("extra", {})
    files_dir = extra.get("files_dir") if extra else None
    if not files_dir or not Path(files_dir).is_dir():
        return False
    shutil.copytree(files_dir, workdir, dirs_exist_ok=True)
    return True


def diff_shape_for(case: Any) -> str:
    """The case's precomputed `diff_shape` (`list_cases()` always sets it),
    defaulting to `"mixed"` for a hand-built case dict that omitted it —
    the fail-safe direction, matching `change_shape.py`'s own bias."""
    extra = case.extra if hasattr(case, "extra") else case.get("extra", {})
    return (extra or {}).get("diff_shape", "mixed")
