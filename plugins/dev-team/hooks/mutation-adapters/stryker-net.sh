#!/usr/bin/env bash
# Stryker.NET (C#) mutation testing adapter.
# Uses the same JSON schema as Stryker JS, so parse_stryker_kills() is shared.
# See lib.sh for adapter contract specification.
# NOTE: stryker_net_run() is intentionally NOT unified with stryker_run() —
#       the CLI surfaces diverge; the shared JSON parser is the stable contract.

ADAPTER_LIB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$ADAPTER_LIB_DIR/lib.sh"

STRYKER_NET_REPORT="${STRYKER_NET_REPORT:-StrykerOutput/mutation-report.json}"

# stryker_net_detect — returns 0 if Stryker.NET is available
stryker_net_detect() {
  # Check dotnet-tools.json
  if [ -f ".config/dotnet-tools.json" ] && grep -q 'dotnet-stryker' ".config/dotnet-tools.json" 2>/dev/null; then
    return 0
  fi
  # Check dotnet stryker --version
  if command -v dotnet &>/dev/null; then
    if dotnet stryker --version &>/dev/null 2>&1; then
      return 0
    fi
  fi
  emit_advisory "MUTATION GATE ADVISORY: Stryker.NET not installed. Run /init-dev-team to install it, or run: dotnet tool install dotnet-stryker"
  return 1
}

# _stryker_net_shard_for_file FILE — echo the stryker-config.shard-*.json path
# whose mutate pattern covers FILE, or empty string if none match.
# Requires python3 and stryker-config.shard-*.json files in the repo root.
_stryker_net_shard_for_file() {
  local changed_file="$1"
  [ -n "$changed_file" ] || return 0
  command -v python3 &>/dev/null || return 0

  for shard_cfg in stryker-config.shard-*.json; do
    [ -f "$shard_cfg" ] || continue
    local src_prefix
    src_prefix=$(python3 -c "
import json, sys
try:
    cfg = json.load(open('$shard_cfg'))['stryker-config']
    pattern = cfg.get('mutate', [''])[0]
    # pattern is like 'src/Foo.Bar/**/*.cs' — extract the prefix before /**
    print(pattern.split('/**')[0])
except Exception:
    pass
" 2>/dev/null)
    [ -n "$src_prefix" ] || continue
    # Match if the changed file starts with the source prefix
    if [[ "$changed_file" == ${src_prefix}/* ]] || [[ "$changed_file" == ${src_prefix}* ]]; then
      echo "$shard_cfg"
      return 0
    fi
  done
}

# stryker_net_run OUTPUT_FILE — runs dotnet stryker and writes zero-kills
#
# Shard-aware execution for large C# repos:
#   If stryker-config.shard-*.json files exist (generated by stryker-setup.py),
#   the adapter detects which shard covers the file changed in the current commit
#   and passes --config-file to scope Stryker to that source project + its tests.
#   This drops wall-clock time from 60–90 min (whole repo) to 5–15 min (one shard).
#
#   Without shard configs, falls back to stryker-config.json if present, or bare
#   dotnet stryker otherwise.
#
# Timeout:
#   ADAPTER_TIMEOUT (default 600s) is the outer process kill timer.
#   600s is generous enough for a single-file scoped run on a large repo.
#   Override: ADAPTER_TIMEOUT=300 ./mutation-gate.sh
stryker_net_run() {
  local output_file="$1"
  local timeout="${ADAPTER_TIMEOUT:-600}"

  mkdir -p "$(dirname "$STRYKER_NET_REPORT")"

  # ── Determine config scope ──────────────────────────────────────────────
  local config_flag=""

  # Find the most recently changed C# source file in the working tree
  local changed_file=""
  changed_file=$(git diff --name-only HEAD 2>/dev/null | grep '\.cs$' | grep -v 'Test\|Spec' | head -1)
  # Fall back to staged changes if HEAD diff is empty (e.g. first commit)
  [ -z "$changed_file" ] && \
    changed_file=$(git diff --cached --name-only 2>/dev/null | grep '\.cs$' | grep -v 'Test\|Spec' | head -1)

  if [ -n "$changed_file" ]; then
    local shard_cfg
    shard_cfg=$(_stryker_net_shard_for_file "$changed_file")
    if [ -n "$shard_cfg" ]; then
      config_flag="--config-file $shard_cfg"
      # Report the shard for transparency in the advisory
      STRYKER_NET_REPORT="StrykerOutput/gate-shard/reports/mutation-report.json"
      mkdir -p "$(dirname "$STRYKER_NET_REPORT")"
    fi
  fi

  # Fall back to master config if no shard matched
  if [ -z "$config_flag" ] && [ -f "stryker-config.json" ]; then
    config_flag="--config-file stryker-config.json"
  fi

  # Build the Stryker command
  # shellcheck disable=SC2206
  local stryker_args=(
    --reporter json
    --coverage-analysis perTest
    --mutation-level Standard
  )
  [ -n "$config_flag" ] && stryker_args=($config_flag "${stryker_args[@]}")

  # Scope further to just the changed file when a shard config was found
  # --mutate narrows within the shard's already-scoped pattern
  if [ -n "$changed_file" ] && [ -n "$config_flag" ]; then
    local basename
    basename=$(basename "$changed_file")
    stryker_args+=(--mutate "**/${basename}")
    STRYKER_NET_REPORT="StrykerOutput/gate-shard/reports/mutation-report.json"
  fi

  # Override output directory so gate runs don't stomp the full pipeline reports
  stryker_args+=(--output StrykerOutput/gate-shard)

  local stryker_exit=0
  _timeout "$timeout" dotnet stryker "${stryker_args[@]}" \
    2>/dev/null || stryker_exit=$?

  if [ "$stryker_exit" -eq 124 ]; then
    emit_advisory "MUTATION GATE SKIPPED: Stryker.NET timed out after ${timeout}s. For large repos, run stryker-setup.py to generate shard configs (reduces scope to one project). Or: ADAPTER_TIMEOUT=<seconds> to extend the limit."
    echo "[]" > "$output_file"
    return 0
  fi

  if [ "$stryker_exit" -ne 0 ] && [ ! -f "$STRYKER_NET_REPORT" ]; then
    emit_advisory "MUTATION GATE ADVISORY: Stryker.NET exited with code $stryker_exit and produced no report. Skipping mutation gate."
    echo "[]" > "$output_file"
    return 0
  fi

  # Reuse parse_stryker_kills from lib.sh — same JSON schema
  parse_stryker_kills "$STRYKER_NET_REPORT" "$output_file"
}
